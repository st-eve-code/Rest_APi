-- =============================================================================
-- ado_test database schema
-- =============================================================================
-- Run automatically by `npm run db:migrate`. Kept as a separate file so you can
-- read -- and hand-edit -- exactly what the app expects to exist.
--
-- PostgreSQL, not portable SQL. See the README for the MySQL equivalent.
-- =============================================================================

-- A custom enum type. Stronger than a VARCHAR with a CHECK constraint because
-- PostgreSQL rejects a bad value itself, and you can never store a typo.
-- To change the allowed values later:
--   ALTER TYPE item_status ADD VALUE 'blocked';
DO $$
BEGIN
  CREATE TYPE item_status AS ENUM ('todo', 'in_progress', 'done');
EXCEPTION
  -- duplicate_object = the type already exists, which is fine: this script is
  -- meant to be re-runnable. (Plain `CREATE TYPE` has no IF NOT EXISTS.)
  WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS items (
  -- UUID primary key, generated by the app (see PostgresItemRepository.create).
  --   * never reused, even across deletes
  --   * not guessable, so item ids cannot be enumerated by a crawler
  --   * merging data from two servers will not collide
  id UUID PRIMARY KEY,

  title VARCHAR(200) NOT NULL,

  -- nullable = optional. NULL and '' are different: NULL means "not provided".
  description TEXT,

  status item_status NOT NULL DEFAULT 'todo',

  -- TIMESTAMPTZ stores an absolute point in time and converts to the reader's
  -- timezone. Plain TIMESTAMP would store a bare time with no zone, which is a
  -- classic source of "it was 5pm yesterday" bugs.
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Stops titles differing only by case or surrounding spaces from slipping in.
  CONSTRAINT items_title_not_blank CHECK (length(btrim(title)) > 0)
);

-- Indexes turn full-table scans into fast lookups.
-- A UNIQUE index creates a database-level guarantee that no title is ever
-- duplicated, even if two servers insert at the same instant.
CREATE UNIQUE INDEX IF NOT EXISTS items_title_unique_idx ON items (lower(btrim(title)));

-- Supports `GET /api/items?status=done`.
CREATE INDEX IF NOT EXISTS items_status_idx ON items (status);

-- Supports `ORDER BY created_at DESC`.
CREATE INDEX IF NOT EXISTS items_created_at_idx ON items (created_at DESC);

-- NOTE: a plain index does NOT speed up `title ILIKE '%x%'` (leading wildcard).
-- For that you need a trigram index:
--   CREATE EXTENSION IF NOT EXISTS pg_trgm;
--   CREATE INDEX items_title_trgm_idx ON items USING GIN (title gin_trgm_ops);

-- =============================================================================
-- AUTHENTICATION
-- =============================================================================

-- Roles live in their own enum, exactly like item_status: PostgreSQL then makes
-- it impossible to store a role that the app does not understand.
DO $$
BEGIN
  CREATE TYPE user_role AS ENUM ('user', 'admin');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS users (
  -- Same reasoning as items.id: UUIDs are not guessable, so one user cannot
  -- enumerate another's id by incrementing a number.
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Stored lowercase; the unique index is what actually enforces uniqueness.
  email VARCHAR(320) NOT NULL,

  -- NEVER a plaintext password. This holds a bcrypt hash, which is one-way:
  -- you cannot log in by sending the value back, only by re-hashing the input
  -- and comparing. See src/features/auth/password.ts.
  password_hash TEXT NOT NULL,

  -- Drives requireRole(). Kept as an enum so a typo cannot grant admin.
  role user_role NOT NULL DEFAULT 'user',

  -- Set when an account is disabled or the password is reset. A disabled
  -- account keeps working until its access token expires (15 min), which is an
  -- accepted trade-off: revoking every live token on each change is far more
  -- expensive than it is worth at this scale. See SECURITY_NOTES.md.
  disabled_at TIMESTAMPTZ,

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Case-insensitive uniqueness: Foo@x.com and foo@x.com are the same inbox.
CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique_idx ON users (lower(email));

-- =============================================================================
-- REFRESH TOKEN REVOCATION LIST
-- =============================================================================
-- JWTs cannot be un-issued. If a refresh token is stolen we have no way to
-- "cancel" it -- so we store a record of every refresh session and refuse to
-- honour one whose row has been deleted or marked used.
--
-- We store only a SHA-256 HASH of the token, never the token itself. A database
-- leak then hands the attacker hashes, which cannot be replayed as tokens.
CREATE TABLE IF NOT EXISTS refresh_tokens (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,

  -- SHA-256 of the refresh token. Deterministic, which is required: we look the
  -- token up by hashing whatever the client sends us.
  token_hash CHAR(64) NOT NULL,

  -- Lets refresh sessions be revoked per-device ("log out this phone only").
  user_agent TEXT,

  -- Free-form slot for the client IP. Useful later for "sign in from a new
  -- location" alerts.
  ip_address INET,

  -- `used_at` is what makes rotation safe: a refresh token is single-use, and a
  -- second attempt to use it is treated as a stolen-token replay.
  used_at TIMESTAMPTZ,

  -- Set on logout. Hard delete also works, because the row is the token.
  revoked_at TIMESTAMPTZ,

  expires_at TIMESTAMPTZ NOT NULL,

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- The lookup path is "given a token hash, is this session still valid?".
CREATE UNIQUE INDEX IF NOT EXISTS refresh_tokens_hash_idx ON refresh_tokens (token_hash);

-- Supports revoking every session for one user at once.
CREATE INDEX IF NOT EXISTS refresh_tokens_user_idx ON refresh_tokens (user_id);

-- Housekeeping: rows for dead sessions are only interesting to an attacker.
CREATE INDEX IF NOT EXISTS refresh_tokens_expires_idx ON refresh_tokens (expires_at);