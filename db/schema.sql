-- A custom enum type. Stronger than a VARCHAR with a CHECK constraint because
-- PostgreSQL rejects a bad value itself, and you can never store a typo.
-- To change the allowed values later:
--   ALTER TYPE item_status ADD VALUE 'blocked';
CREATE TYPE item_status AS ENUM ('todo', 'in_progress', 'done');

CREATE TABLE IF NOT EXISTS items (
  -- UUID primary key, generated by the app (see PostgresItemRepository.create).
  --   * never reused, even across deletes
  --   * not guessable, so item ids cannot be enumerated by a crawler
  --   * merging data from two servers will not collide
  id UUID PRIMARY KEY,

  title VARCHAR(200) NOT NULL,

  -- nullable = optional. NULL and '' are different: NULL means "not provided".
  description TEXT,

  status item_status NOT NULL DEFAULT 'todo',

  -- TIMESTAMPTZ stores an absolute point in time and converts to the reader's
  -- timezone. Plain TIMESTAMP would store a bare time with no zone, which is a
  -- classic source of "it was 5pm yesterday" bugs.
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Stops titles differing only by case or surrounding spaces from slipping in.
  CONSTRAINT items_title_not_blank CHECK (length(btrim(title)) > 0)
);

-- Indexes turn full-table scans into fast lookups.
-- A UNIQUE index creates a database-level guarantee that no title is ever
-- duplicated, even if two servers insert at the same instant.
CREATE UNIQUE INDEX IF NOT EXISTS items_title_unique_idx ON items (lower(btrim(title)));

-- Supports `GET /api/items?status=done`.
CREATE INDEX IF NOT EXISTS items_status_idx ON items (status);

-- Supports `ORDER BY created_at DESC`.
CREATE INDEX IF NOT EXISTS items_created_at_idx ON items (created_at DESC);

